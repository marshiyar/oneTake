// PulseAudio backend is compiled only when its dev headers are installed (libpulse-dev); otherwise
// MpvfxAudio builds without CPulse and `#if canImport(CPulse)` drops PulseAudioOutput.
let hasPulseHeaders = FileManager.default.fileExists(atPath: "/usr/include/pulse/simple.h")
var audioDependencies: [Target.Dependency] = []
var pulseTargets: [Target] = []
if hasPulseHeaders {
    pulseTargets.append(.systemLibrary(name: "CPulse", path: "Sources/CPulse", pkgConfig: "libpulse-simple",
                                       providers: [.apt(["libpulse-dev"])]))
    audioDependencies.append(.target(name: "CPulse", condition: .when(platforms: [.linux])))
}

// GPU grading (MpvfxMetal: Metal kernels in Sources/MpvfxMetal/Shaders/MpvfxColor.metal) exists only in macOS builds;
// Linux and Windows builds never see the target and grade on the CPU port in MpvfxColor.
var metalTargets: [Target] = []
var metalDependencies: [Target.Dependency] = []
#if os(macOS)
metalTargets.append(.target(name: "MpvfxMetal", dependencies: ["CMpvfxColorShared"],
                            resources: [.process("Shaders/MpvfxColor.metal"), .copy("Shaders/MpvfxColorShared.h")]))
metalDependencies.append("MpvfxMetal")
#endif

// GPU grading on Linux: Vulkan compute (CMpvfxVulkan, kernels generated by scripts/gpu/gen-compute-shaders.py from the
// Metal shading body) when the Vulkan headers are installed (libvulkan-dev); otherwise MpvfxColor builds without it and
// grades on the CPU. Nothing links libvulkan: CMpvfxVulkan opens the loader at run time, so the app also starts on a
// machine without it. CVulkan only declares the system headers (no pkg-config: its flags would link the loader).
var vulkanTargets: [Target] = []
var gpuDependencies: [Target.Dependency] = []
#if os(Linux)
if FileManager.default.fileExists(atPath: "/usr/include/vulkan/vulkan.h") {
    vulkanTargets.append(.systemLibrary(name: "CVulkan", path: "Sources/CVulkan", providers: [.apt(["libvulkan-dev"])]))
    vulkanTargets.append(.target(name: "CMpvfxVulkan", dependencies: ["CVulkan", "CMpvfxColorShared"],
                                 linkerSettings: [.linkedLibrary("dl"), .linkedLibrary("pthread")]))
    gpuDependencies.append("CMpvfxVulkan")
}
#endif

// The media engine through the app's adapter (prebuilt library; see engineTargets below).
let mediaEngine: Target.Dependency = "OneTakeMedia"

// Windows graphics, audio and shell APIs (Direct2D, DirectWrite, WIC, WASAPI, item dialogs, the Direct3D 11 compute
// grade) behind a flat C interface:
// C++ COM code in Sources/CMpvfxWin32 that compiles to nothing on Linux and macOS, so only Windows builds depend on it.
let win32: Target.Dependency = .target(name: "CMpvfxWin32", condition: .when(platforms: [.windows]))

// The keyframe engine through the app's adapter (prebuilt library; see engineTargets below).
let keyframeEngine: Target.Dependency = "OneTakeKeyframes"

// The platform-dependent lists are joined here, outside the Package literal: inside it, every `[...] + list` adds to one
// expression the manifest compiler must type-check, and with the GPU lists added Xcode's swiftc gave up on it.
let colorDependencies: [Target.Dependency] = ["MpvfxShared", "CMpvfxColorShared", win32] + metalDependencies + gpuDependencies
let audioTargetDependencies: [Target.Dependency] = ["MpvfxAudioGraph", "MpvfxShared", mediaEngine, win32] + audioDependencies
let colorTestDependencies: [Target.Dependency] = ["MpvfxColor", "MpvfxShared", "CMpvfxColorShared"] + metalDependencies + gpuDependencies
let playerTestDependencies: [Target.Dependency] =
    ["MpvfxPlayer", "MpvfxTimeline", "MpvfxCanvas", "MpvfxShared", keyframeEngine, "MpvfxPanels", "MpvfxColor"] + metalDependencies
let platformTargets: [Target] = pulseTargets + metalTargets + vulkanTargets

// The media and keyframe engines are proprietary dynamic libraries, not built here: `python3 scripts/fetch-binaries.py`
// downloads the versions pinned in binaries.lock, checks their SHA-256 and unpacks each into .binaries/<component>/
// (include/ the C header, lib/ the library and on Windows its import library, bin/ the DLL on Windows).
// CMediaEngine and CKeyframeEngine are their C interfaces; OneTakeMedia and OneTakeKeyframes are the app's own Swift
// adapters over those headers. The installers copy the libraries next to the app (docs/PACKAGING.md).
#if os(Windows)
// The linker wants a native Windows path, so the folder is cut from #filePath itself (either separator).
let manifestDir: String = {
    let path = #filePath
    guard let cut = path.lastIndex(where: { $0 == "\\" || $0 == "/" }) else { preconditionFailure("no folder in \(path)") }
    return String(path[..<cut])
}()
let pathSeparator = "\\"
#else
let manifestDir = URL(fileURLWithPath: #filePath).deletingLastPathComponent().path
let pathSeparator = "/"
#endif

func engineLibraryDir(_ component: String) -> String {
    [manifestDir, ".binaries", component, "lib"].joined(separator: pathSeparator)
}

func engineLinkerSettings(_ component: String) -> [LinkerSetting] {
    let dir = engineLibraryDir(component)
    #if os(Windows)
    return [.unsafeFlags(["-L", dir])]   // the DLL is found next to the exe, or on PATH for tests
    #else
    // The rpath lets `swift run` and `swift test` load the library where it was unpacked; the installers replace it.
    return [.unsafeFlags(["-L", dir, "-Xlinker", "-rpath", "-Xlinker", dir])]
    #endif
}

let engineTargets: [Target] = [
    .systemLibrary(name: "CMediaEngine", path: "Sources/CMediaEngine"),
    .target(name: "OneTakeMedia", dependencies: ["CMediaEngine"], linkerSettings: engineLinkerSettings("media")),
    .systemLibrary(name: "CKeyframeEngine", path: "Sources/CKeyframeEngine"),
    .target(name: "OneTakeKeyframes", dependencies: ["CKeyframeEngine"], linkerSettings: engineLinkerSettings("keyframes")),
]

